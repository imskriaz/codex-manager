import assert from 'node:assert/strict';
import path from 'node:path';

export async function checkProjectCreationUi(page, { origin, width, output }) {
  const started = Date.now();
  await page.goto(origin + '/workspace');
  await page.locator('.cli-workspace').waitFor();
  const show = page.getByRole('button', { name: 'Show sessions sidebar', exact: true });
  if (await show.isVisible()) await show.click();
  const projects = page.getByRole('button', { name: 'Show projects and sessions', exact: true });
  if (await projects.isVisible()) await projects.click();
  await page.getByRole('button', { name: 'Expand empty-project-with-a-long-name', exact: true }).waitFor();
  assert.equal(await page.locator('.cli-create-project').count(), 0, 'Creation stays in the project picker');
  await page.getByRole('button', { name: 'New chat', exact: true }).click();
  const picker = page.getByRole('combobox', { name: 'Project', exact: true });
  await picker.click();
  const search = page.getByRole('searchbox', { name: 'Search project', exact: true });
  await search.waitFor();
  assert.ok(await search.evaluate(element => element === document.activeElement), 'Search gets focus');
  const selected = await picker.getAttribute('data-value');
  await search.fill('empty-project');
  await page.locator('.project-picker-popover [role=option][data-value="D:/demo"]').waitFor({ state: 'detached' });
  assert.equal(await page.locator('.project-picker-popover').getByRole('option').count(), 2, 'Search retains no-folder and matching folder');
  await search.fill('not-a-folder');
  await page.getByText('No matching folders', { exact: true }).waitFor();
  await search.fill('');
  await page.getByRole('button', { name: 'Remove empty-project-with-a-long-name from recent', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Remove empty-project-with-a-long-name from recent', exact: true }).click();
  const confirmation = page.getByRole('alertdialog', { name: 'Remove empty-project-with-a-long-name from recent projects', exact: true });
  await confirmation.waitFor();
  await page.screenshot({ path: path.join(output, `project-remove-confirm-${width}.png`) });
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click();
  await confirmation.waitFor({ state: 'detached' });
  await picker.click();
  await page.getByRole('button', { name: 'Remove empty-project-with-a-long-name from recent', exact: true }).click();
  await confirmation.getByRole('button', { name: 'Remove', exact: true }).click();
  await confirmation.waitFor({ state: 'detached' });
  await picker.click();
  assert.equal(await page.locator('.project-picker-popover').getByRole('option').filter({ hasText: 'empty-project-with-a-long-name' }).count(), 0);
  assert.equal(await picker.getAttribute('data-value'), selected, 'Removal preserves the current project');
  await page.keyboard.press('Escape');
  assert.ok(await picker.evaluate(element => element === document.activeElement), 'Escape restores trigger focus');
  await picker.click();
  assert.equal(await page.locator('.project-picker-popover').getByRole('option').filter({ hasText: 'empty-project-with-a-long-name' }).count(), 0, 'Removal persists on reopening');
  await search.fill('empty-project');
  await page.locator('.project-picker-popover [role=option][data-value="D:/empty-project-with-a-long-name"]').waitFor();
  await search.press('Enter');
  assert.equal(await picker.getAttribute('data-value'), 'D:/empty-project-with-a-long-name', 'Search can still select a project removed from recents');
  await picker.click(); await search.fill('demo'); await search.press('ArrowDown'); await page.keyboard.press('End'); await page.keyboard.press('Enter');
  assert.equal(await picker.getAttribute('data-value'), 'D:/demo', 'Keyboard selects the folder');
  await picker.click();
  const bounds = await page.locator('.project-picker-popover').boundingBox();
  assert.ok((await search.boundingBox()).height <= 31, 'Search stays compact');
  assert.equal(await page.locator('.project-picker-check, .project-picker-notice').count(), 0, 'No ticks or status line below the list');
  const viewport = page.viewportSize();
  assert.ok(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= viewport.width + 1 && bounds.y + bounds.height <= viewport.height + 1, 'Picker stays inside the viewport');
  await page.screenshot({ path: path.join(output, `project-picker-${width}.png`) });
  await page.keyboard.press('Escape');
  await page.getByRole('combobox', { name: 'Project', exact: true }).click(); await page.getByRole('button', { name: 'Create new', exact: true }).click();
  const modal = page.getByRole('dialog', { name: 'Add Project', exact: true });
  await modal.waitFor();
  assert.equal(await modal.getByRole('textbox').count(), 1, 'Only the project folder field is shown');
  const projectFolder = modal.getByRole('textbox', { name: 'Project folder', exact: true });
  await projectFolder.fill('D:/Projects');
  await modal.getByRole('button', { name: 'Browse folders…', exact: true }).click();
  const folders = page.getByRole('dialog', { name: 'Select project folder', exact: true });
  await folders.waitFor();
  await folders.getByRole('button', { name: 'Home', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).waitFor();
  assert.ok(await folders.getByRole('button', { name: 'Select folder', exact: true }).isEnabled());
  await page.keyboard.press('Tab');
  assert.ok(await folders.evaluate(dialog => dialog.contains(document.activeElement)), 'Keyboard focus stays in the folder picker');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
  await page.screenshot({ path: path.join(output, `project-folder-picker-${width}.png`) });
  await folders.getByRole('button', { name: 'New folder', exact: true }).click();
  let newFolderModal = page.getByRole('dialog', { name: 'New folder', exact: true });
  await newFolderModal.waitFor();
  const folderName = newFolderModal.getByRole('textbox', { name: 'Folder name', exact: true });
  await folderName.fill('Cancelled folder');
  await newFolderModal.locator('form').getByRole('button', { name: 'Cancel new folder', exact: true }).click();
  await folders.getByRole('status').filter({ hasText: 'Folder creation cancelled.' }).waitFor();
  assert.equal(await page.evaluate(() => window.__uiActions.filter(action => action.action === 'createWorkspaceFolder').length), 0);
  await folders.getByRole('button', { name: 'New folder', exact: true }).click();
  newFolderModal = page.getByRole('dialog', { name: 'New folder', exact: true });
  await newFolderModal.waitFor();
  await folderName.fill('Existing');
  await newFolderModal.getByRole('button', { name: 'Create folder', exact: true }).click();
  await folders.getByRole('alert').filter({ hasText: 'already exists' }).waitFor();
  assert.equal(await folderName.inputValue(), 'Existing', 'Failure preserves the draft');
  await folderName.fill('New folder');
  assert.ok(await newFolderModal.evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth + 2));
  await page.screenshot({ path: path.join(output, `project-new-folder-form-${width}.png`) });
  await newFolderModal.getByRole('button', { name: 'Create folder', exact: true }).click();
  await folders.getByRole('status').filter({ hasText: 'Folder created: D:/New folder' }).waitFor();
  assert.equal(await folders.locator('.folder-picker-selection code').innerText(), 'D:/New folder');
  assert.ok(await folders.getByRole('button', { name: 'Select folder', exact: true }).isEnabled());
  await page.screenshot({ path: path.join(output, `project-new-folder-created-${width}.png`) });
  await page.keyboard.press('Escape');
  await folders.waitFor({ state: 'detached' });
  assert.ok(await modal.isVisible(), 'Escape closes only the folder picker');
  assert.equal(await projectFolder.inputValue(), 'D:/Projects');
  await modal.getByRole('button', { name: 'Browse folders…', exact: true }).click();
  await folders.waitFor();
  await folders.getByRole('button', { name: 'Home', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).click();
  await folders.locator('.folder-picker-selection code').filter({ hasText: 'D:/Projects' }).waitFor();
  await folders.getByRole('button', { name: 'Up one level', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).waitFor();
  const folderPath = folders.getByRole('textbox', { name: 'Folder path', exact: true });
  await folderPath.fill('D:/Projects');
  assert.ok(await folders.getByRole('button', { name: 'Select folder', exact: true }).isDisabled(), 'An unvisited path cannot select a stale folder');
  await folderPath.press('Enter');
  await folders.locator('.folder-picker-selection code').filter({ hasText: 'D:/Projects' }).waitFor();
  await folders.getByRole('button', { name: 'Select folder', exact: true }).click();
  await folders.waitFor({ state: 'detached' });
  assert.equal(await modal.getByRole('textbox', { name: 'Project folder', exact: true }).inputValue(), 'D:/Projects');
  assert.equal(await modal.locator('.create-project-destination code').innerText(), 'D:/Projects');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
  await page.screenshot({ path: path.join(output, `project-browser-${width}.png`) });
  assert.ok(await modal.getByRole('button', { name: 'Add project', exact: true }).isEnabled());
  assert.equal(await modal.locator('.create-project-destination code').innerText(), 'D:/Projects');
  await page.screenshot({ path: path.join(output, `project-existing-folder-${width}.png`) });
  await modal.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.evaluate(() => window.__uiActions.filter(action => action.action === 'createWorkspaceProject').length), 0, 'Folder selection never creates a project');
  const showAgain = page.getByRole('button', { name: 'Show sessions sidebar', exact: true });
  if (await showAgain.isVisible()) await showAgain.click();
  await page.evaluate(() => {
    window.__uiSessions.splice(0);
    dispatchEvent(new MessageEvent('message', { data: { type: 'dashboard:action-result', action: 'listCodexCliSessions', requestId: 'dashboard-auto-fixture', status: 'completed', payload: { cliSessions: [] } } }));
  });
  await page.getByRole('button', { name: 'New chat', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Expand empty-project-with-a-long-name', exact: true }).waitFor();
  await page.goto(origin + '/tasks');
  const hideSidebar = page.getByRole('button', { name: 'Hide sessions sidebar', exact: true });
  if (width < 760 && await hideSidebar.isVisible()) await hideSidebar.click();
  const taskPicker = page.getByRole('combobox', { name: 'Task project', exact: true });
  await taskPicker.click();
  const taskSearch = page.getByRole('searchbox', { name: 'Search task project', exact: true });
  await taskSearch.waitFor();
  assert.equal(await page.locator('.project-picker-popover').getByRole('option').filter({ hasText: 'empty-project-with-a-long-name' }).count(), 0, 'Task picker shares removed recents with the composer');
  await page.screenshot({ path: path.join(output, `task-project-picker-${width}.png`) });
  await taskSearch.fill('empty-project');
  await page.locator('.project-picker-popover').getByRole('option').filter({ hasText: 'empty-project-with-a-long-name' }).waitFor();
  await page.keyboard.press('Escape');
  await taskPicker.click(); await page.getByRole('button', { name: 'Create new', exact: true }).click();
  await modal.waitFor();
  await modal.getByRole('button', { name: 'Cancel', exact: true }).click();
  console.log(JSON.stringify({ width, durationMs: Date.now() - started, checks: 'Empty project and zero-session picker, separate folder modal, focus, Escape preserves draft, Home/Up/path navigation, folder creation/collision/cancellation, selection, no real writes' }));
}
