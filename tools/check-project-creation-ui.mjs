import assert from 'node:assert/strict';
import path from 'node:path';

export async function checkProjectCreationUi(page, { origin, width, output }) {
  const started = Date.now();
  await page.goto(origin + '/workspace');
  await page.locator('.cli-workspace').waitFor();
  const show = page.getByRole('button', { name: 'Show sessions sidebar', exact: true });
  if (await show.isVisible()) await show.click();
  const projects = page.getByRole('button', { name: 'Show projects and sessions', exact: true });
  if (await projects.isVisible()) await projects.click();
  await page.getByRole('button', { name: 'Expand empty-project-with-a-long-name', exact: true }).waitFor();
  assert.equal(await page.locator('.cli-create-project').count(), 0, 'Creation stays in the project picker');
  await page.getByRole('button', { name: 'New chat', exact: true }).click();
  await page.getByRole('combobox', { name: 'Project', exact: true }).selectOption('__create_workspace_project__');
  const modal = page.getByRole('dialog', { name: 'Create new project', exact: true });
  await modal.waitFor();
  await modal.getByRole('textbox', { name: 'Project name', exact: true }).fill('folder-preview');
  await modal.getByRole('button', { name: 'Browse folders…', exact: true }).click();
  const folders = page.getByRole('dialog', { name: 'Select parent folder', exact: true });
  await folders.waitFor();
  await folders.getByRole('button', { name: 'Home', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).waitFor();
  assert.ok(await folders.getByRole('button', { name: 'Select folder', exact: true }).isEnabled());
  await page.keyboard.press('Tab');
  assert.ok(await folders.evaluate(dialog => dialog.contains(document.activeElement)), 'Keyboard focus stays in the folder picker');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
  await page.screenshot({ path: path.join(output, `project-folder-picker-${width}.png`) });
  await page.keyboard.press('Escape');
  await folders.waitFor({ state: 'detached' });
  assert.ok(await modal.isVisible(), 'Escape closes only the folder picker');
  assert.equal(await modal.getByRole('textbox', { name: 'Project name', exact: true }).inputValue(), 'folder-preview');
  await modal.getByRole('button', { name: 'Browse folders…', exact: true }).click();
  await folders.waitFor();
  await folders.getByRole('button', { name: 'Home', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).click();
  await folders.locator('.folder-picker-selection code').filter({ hasText: 'D:/Projects' }).waitFor();
  await folders.getByRole('button', { name: 'Up one level', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).waitFor();
  await folders.getByRole('button', { name: 'Refresh folders', exact: true }).click();
  await folders.getByRole('button', { name: 'Open Projects', exact: true }).waitFor();
  const folderPath = folders.getByRole('textbox', { name: 'Folder path', exact: true });
  await folderPath.fill('D:/Projects');
  assert.ok(await folders.getByRole('button', { name: 'Select folder', exact: true }).isDisabled(), 'An unvisited path cannot select a stale folder');
  await folderPath.press('Enter');
  await folders.locator('.folder-picker-selection code').filter({ hasText: 'D:/Projects' }).waitFor();
  await folders.getByRole('button', { name: 'Select folder', exact: true }).click();
  await folders.waitFor({ state: 'detached' });
  assert.equal(await modal.getByRole('textbox', { name: 'Parent folder', exact: true }).inputValue(), 'D:/Projects');
  assert.ok(await modal.locator('.create-project-destination').innerText().then(text => text.includes('D:/Projects/folder-preview')));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
  await page.screenshot({ path: path.join(output, `project-browser-${width}.png`) });
  await modal.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.evaluate(() => window.__uiActions.filter(action => action.action === 'createWorkspaceProject').length), 0, 'Folder selection never creates a project');
  const showAgain = page.getByRole('button', { name: 'Show sessions sidebar', exact: true });
  if (await showAgain.isVisible()) await showAgain.click();
  await page.evaluate(() => {
    window.__uiSessions.splice(0);
    dispatchEvent(new MessageEvent('message', { data: { type: 'dashboard:action-result', action: 'listCodexCliSessions', requestId: 'dashboard-auto-fixture', status: 'completed', payload: { cliSessions: [] } } }));
  });
  await page.getByRole('button', { name: 'New chat', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Expand empty-project-with-a-long-name', exact: true }).waitFor();
  console.log(JSON.stringify({ width, durationMs: Date.now() - started, checks: 'Empty project and zero-session picker, separate folder modal, focus, Escape preserves draft, Home/Up/refresh/path navigation, selection, cancellation, no real writes' }));
}
