import assert from 'node:assert/strict';
import path from 'node:path';

// Uses the intercepted host in check-responsive-ui; no native cleanup runs.
export async function checkMaintenanceUi(page, { origin, width, height, output }) {
  const exact = name => ({ name, exact: true });
  const actionCount = action => page.evaluate(action => window.__uiActions.filter(item => item.action === action).length, action);
  const open = async () => {
    const desktop = page.locator('#settingsOpenButton');
    if (await desktop.isVisible()) await desktop.click();
    else { await page.locator('.dashboard-mobile-actions > summary').click(); await page.getByRole('menuitem', exact('Settings')).click(); }
    await page.locator('#settings-tab-tools').click();
  };
  const start = async () => {
    const archive = page.getByRole('region', exact('Archive manager'));
    await archive.getByRole('group', exact('Tool items')).getByRole('checkbox').first().check();
    await archive.getByRole('button', exact('Restore selected')).click();
    await archive.getByRole('button', exact('Restore selected')).click();
  };
  const progress = async (patch, deviceId = 'fixture-peer') => page.evaluate(({ patch, deviceId }) => {
    window.dispatchEvent(new MessageEvent('message', { data: {type:'dashboard:maintenance-progress',deviceId,job:{...window.__maintenanceJob,...patch}} }));
  }, {patch,deviceId});
  await page.clock.install();
  await page.goto(`${origin}/`, {waitUntil:'domcontentloaded'});
  await page.locator('#settingsOpenButton').waitFor({state:'attached'});
  await page.evaluate(() => {
    window.__uiSnapshot.connectedPeers = [...(window.__uiSnapshot.connectedPeers || []), {id:'fixture-peer',name:'Fixture peer',connected:true,local:false,sessionCount:0}];
    window.dispatchEvent(new MessageEvent('message', {data:{type:'dashboard:snapshot',state:window.__uiSnapshot}}));
  });
  const showSessions = page.getByRole('button', exact('Show sessions sidebar'));
  if (await showSessions.isVisible()) await showSessions.click();
  await page.getByRole('combobox', exact('System')).selectOption('fixture-peer');
  const closeSessions = page.getByRole('button', exact('Close sessions sidebar'));
  if (await closeSessions.isVisible()) await page.getByRole('button', exact('Hide sessions sidebar')).click();
  await open();
  assert.equal(await page.locator('.maintenance-storage-operations > button').count(), 7, 'Every tool uses the compact navigator');
  for (const [title, clear] of [['Archive manager','Clear all archives'],['Conversation cleanup','Clear all Codex data'],['Goal manager','Clear all goals'],['Shell snapshot cleanup','Clean old shell snapshots']]) {
    await page.getByRole('button', exact(title+' Manage')).click();
    const tool = page.getByRole('region', exact(title)), rows = tool.getByRole('group', exact('Tool items')).getByRole('checkbox');
    await rows.first().waitFor();
    assert.equal(await page.getByRole('dialog').last().getByText(title, {exact:true}).count(), 1, 'The tool title appears once');
    const system = await tool.locator('.maintenance-system').innerText();
    assert.ok(system.length > 0, 'The source system remains visible, including privacy masking');
    assert.equal(await tool.getByText(system,{exact:true}).count(), 1, 'The source system appears once');
    assert.equal(await tool.locator('.maintenance-footer').count(), 0, 'No disabled action footer');
    assert.equal(await tool.getByRole('button', exact('Delete selected')).count(), 0, 'Selection actions appear when useful');
    const rowHeight = await tool.locator('.maintenance-item').first().evaluate(row=>row.getBoundingClientRect().height);
    assert.ok(rowHeight <= 44, 'Rows stay compact');
    await tool.locator('summary[aria-label="More cleanup actions"]').click();
    await tool.getByRole('button', exact(clear)).click();
    await tool.getByRole('region', exact('Confirm maintenance')).waitFor();
    assert.equal(await actionCount('runMaintenance'), 0, 'Bulk cleanup still requires explicit confirmation');
    await tool.getByRole('button', exact('Cancel')).click();
    await tool.locator('summary[aria-label="More cleanup actions"]').click();
    await page.keyboard.press('Escape');
    assert.equal(await tool.locator('.maintenance-more[open]').count(), 0, 'Escape closes the action menu first');
    await tool.getByRole('button', exact('All tools')).click();
  }
  await page.getByRole('button', exact('Archive manager Manage')).click();
  const compact = page.getByRole('region', exact('Archive manager'));
  await compact.getByRole('checkbox', exact('Select page')).check();
  await compact.getByText('50 selected', {exact:true}).waitFor();
  await compact.getByRole('button', exact('Next')).click();
  await compact.getByText('51–63 of 63', {exact:true}).waitFor();
  await compact.getByRole('checkbox', exact('Select page')).check();
  await compact.getByText('63 selected', {exact:true}).waitFor();
  await compact.getByRole('checkbox', exact('Select page')).uncheck();
  await compact.getByText('50 selected', {exact:true}).waitFor();
  await compact.getByRole('button', exact('Clear selection')).click();
  await compact.getByRole('searchbox').fill('no matching archive');
  await compact.getByRole('searchbox').press('Enter');
  await compact.getByText('No matching items.',{exact:true}).waitFor();
  assert.equal(await compact.getByRole('checkbox', exact('Select page')).isDisabled(), true);
  await compact.getByRole('button', exact('All tools')).click();
  await page.evaluate(()=>{window.__maintenanceCount=0;});
  await page.getByRole('button', exact('Archive manager Manage')).click();
  await compact.getByText('Nothing to clean up.',{exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.maintenance-search button[aria-label="Refresh"]')?.disabled===false && document.querySelector('.maintenance-items')?.getAttribute('aria-busy')==='false');
  await compact.getByRole('button', exact('Refresh')).focus();
  assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')), 'Refresh', 'The settled empty view can focus Refresh');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement?.outerHTML), await compact.locator('summary[aria-label="More cleanup actions"]').evaluate(element=>element.outerHTML), 'The action menu participates in modal keyboard navigation');
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button', exact('Close tool')).evaluate(element=>element===document.activeElement), true, 'The last tool control wraps focus within its modal');
  await page.keyboard.press('Shift+Tab');
  await compact.locator('summary[aria-label="More cleanup actions"]').click();
  assert.equal(await compact.getByRole('button', exact('Clear all archives')).isDisabled(), true);
  await compact.getByRole('button', exact('All tools')).click();
  await page.evaluate(()=>{window.__maintenanceCount=2;window.__maintenanceLongTitle=true;});
  await page.getByRole('button', exact('Archive manager Manage')).click();
  await compact.getByRole('group', exact('Tool items')).getByRole('checkbox').last().waitFor();
  assert.ok(await compact.locator('.maintenance-item strong').first().evaluate(element=>element.scrollWidth>element.clientWidth), 'Long titles truncate visually without widening the dialog');
  await page.screenshot({path:path.join(output,`maintenance-compact-${width}x${height}.png`),animations:'disabled'});
  await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'));
  await page.screenshot({path:path.join(output,`maintenance-compact-dark-${width}x${height}.png`),animations:'disabled'});
  await page.evaluate(()=>document.documentElement.setAttribute('data-theme','light'));
  await compact.getByRole('group', exact('Tool items')).getByRole('checkbox').first().check();
  assert.equal(await compact.getByRole('checkbox', exact('Select page')).evaluate(input=>input.indeterminate), true, 'Partial page selection remains visible');
  await page.screenshot({path:path.join(output,`maintenance-selected-${width}x${height}.png`),animations:'disabled'});
  await compact.getByRole('button', exact('Delete selected')).click();
  await compact.getByText('Permanently delete 1 item?',{exact:true}).waitFor();
  assert.equal(await actionCount('runMaintenance'), 0, 'Selected cleanup also preserves confirmation');
  await compact.getByRole('button', exact('Cancel')).click();
  await compact.getByRole('button', exact('All tools')).click();
  await page.evaluate(()=>{delete window.__maintenanceCount;window.__maintenanceLongTitle=false;});
  await page.getByRole('region', exact('Storage Management')).getByRole('button', exact('Open summary')).click();
  const storage = page.getByRole('region', exact('Codex storage check'));
  await storage.getByRole('region', exact('Database allocation')).waitFor();
  for (const label of ['Live pages','Reusable inside databases','Write-ahead logs (WAL)','Shared-memory files']) await storage.getByText(label,{exact:true}).waitFor();
  await page.evaluate(() => {window.__storagePartial=true;});
  await storage.getByRole('button',exact('Refresh report')).click();
  await storage.getByText('Database allocation · partial',{exact:true}).waitFor();
  await storage.getByText('Incomplete inspection',{exact:true}).waitFor();
  await storage.getByRole('button',exact('All tools')).click();
  await page.evaluate(() => {window.__storagePartial=false;});
  await page.getByRole('button', exact('Codex UI startup Inspect')).click();
  const startup = page.getByRole('region', exact('Codex UI startup'));
  await startup.getByText('Healthy · 2 MB', {exact:true}).waitFor();
  await startup.getByRole('button', exact('Open fresh Codex panel')).click();
  await startup.getByText('Open request completed. Check that the new panel finishes loading.', {exact:true}).waitFor();
  await page.evaluate(() => {window.__failCodexReopen=true;});
  await startup.getByRole('button', exact('Open fresh Codex panel')).click();
  await startup.getByRole('alert').filter({hasText:'Codex could not open in this host.'}).waitFor();
  assert.equal(await actionCount('reopenCodexUi'), 2);
  await startup.getByRole('button', exact('All tools')).click();
  await page.evaluate(() => {window.__holdNextMaintenancePreview=true;});
  await page.getByRole('button', exact('Archive manager Manage')).click();
  await page.waitForFunction(() => !!window.__heldMaintenancePreview);
  await page.getByRole('button', exact('All tools')).click();
  await page.keyboard.press('Escape');
  const hiddenPageReads = await actionCount('getMaintenancePage');
  await page.evaluate(() => window.dispatchEvent(new MessageEvent('message',{data:window.__heldMaintenancePreview})));
  await page.clock.fastForward(2000);
  assert.equal(await actionCount('getMaintenancePage'), hiddenPageReads, 'A preview finishing after Settings closes does not start a hidden page read');
  await open();
  await page.getByRole('button', exact('Archive manager Manage')).click();
  const archive = page.getByRole('region', exact('Archive manager'));
  await archive.getByRole('group', exact('Tool items')).getByRole('checkbox').first().waitFor();
  assert.equal(await archive.getByRole('group', exact('Tool items')).getByRole('checkbox').count(), 50);
  const reads = await actionCount('getMaintenancePage');
  await archive.getByRole('searchbox').fill('task 62');
  await page.clock.fastForward(700);
  assert.equal(await actionCount('getMaintenancePage'), reads, 'Typing does not start a debounce timer or background request');
  await archive.getByRole('searchbox').press('Enter');
  await page.waitForFunction(() => document.querySelectorAll('.maintenance-items input').length === 1);
  await page.evaluate(() => {window.__keepMaintenanceRunning=true;window.__loseMaintenanceAck=true;window.__progressBeforeAck=true;});
  await start();
  await archive.getByText('Restore in progress', {exact:true}).waitFor();
  await page.waitForFunction(() => window.__uiActions.some(item => item.action === 'getMaintenanceStatus'));
  const statusReads = await actionCount('getMaintenanceStatus');
  await page.clock.fastForward(8000);
  assert.equal(await actionCount('getMaintenanceStatus'), statusReads, 'Visible running work does not poll');
  await progress({status:'completed',processed:1,cleared:1,revision:100}, 'other-pc');
  assert.equal(await archive.getByRole('button', exact('Cancel operation')).isEnabled(), true, 'Another PC cannot complete this job');
  await archive.getByRole('button', exact('Cancel operation')).click();
  await archive.getByText('Cancelled. Remaining items were kept.', {exact:true}).waitFor();
  await progress({status:'running',processed:0,cleared:0,revision:0});
  assert.equal(await archive.getByRole('button', exact('Cancel operation')).count(), 0, 'Late progress cannot restart a finished job');
  await archive.getByRole('button', exact('Review current data')).click();
  await archive.getByRole('group', exact('Tool items')).getByRole('checkbox').first().waitFor();
  await page.evaluate(() => {window.__progressBeforeAck=false;});
  await start();
  await page.waitForFunction(() => window.__uiActions.filter(item => item.action === 'runMaintenance').length === 2);
  await page.clock.fastForward(31000);
  await archive.getByText(/Connection timed out/).waitFor();
  await archive.getByRole('button', exact('Check operation status')).click();
  await archive.getByText('Restore in progress', {exact:true}).waitFor();
  assert.equal(await actionCount('runMaintenance'), 2, 'Missing acknowledgement is recovered by read-only preview lookup without replay');
  await archive.getByRole('button', exact('All tools')).click();
  await page.keyboard.press('Escape');
  await page.locator('.overlay.open').waitFor({state:'detached'});
  const hiddenReads = await actionCount('getMaintenanceStatus');
  await page.clock.fastForward(8000);
  assert.equal(await actionCount('getMaintenanceStatus'), hiddenReads, 'Closed Settings does not read progress');
  await open();
  await page.getByRole('button', exact('View progress')).click();
  await archive.getByText('Restore in progress', {exact:true}).waitFor();
  await page.evaluate(() => window.dispatchEvent(new MessageEvent('message', {data:{type:'dashboard:connection',connected:false}})));
  await page.waitForFunction(() => document.querySelector('.settings-offline-fieldset')?.disabled);
  assert.equal(await archive.getByRole('button', exact('Cancel operation')).isDisabled(), true, 'Offline cleanup actions stay disabled');
  await page.evaluate(() => {
    window.__uiSnapshot.connectedPeers.find(peer => peer.id === 'fixture-peer').connected = false;
    window.dispatchEvent(new MessageEvent('message', {data:{type:'dashboard:snapshot',state:window.__uiSnapshot}}));
    window.dispatchEvent(new MessageEvent('message', {data:{type:'dashboard:connection',connected:true}}));
  });
  await page.waitForFunction(() => document.querySelector('.settings-offline-fieldset')?.disabled);
  assert.equal(await archive.getByRole('button', exact('Cancel operation')).isDisabled(), true, 'A disconnected peer disables cleanup even while the browser is online');
  await page.evaluate(() => {
    window.__maintenanceRestarted=true;
    window.__uiSnapshot.connectedPeers.find(peer => peer.id === 'fixture-peer').connected = true;
    window.dispatchEvent(new MessageEvent('message', {data:{type:'dashboard:snapshot',state:window.__uiSnapshot}}));
  });
  await archive.getByText(/host restarted or became unavailable/).waitFor();
  assert.equal(await actionCount('runMaintenance'), 2, 'Reconnect and host restart never replay a mutation');
  await progress({status:'completed',processed:1,cleared:1,revision:100});
  await archive.getByText('Restore complete', {exact:true}).waitFor();
  await progress({status:'running',processed:0,cleared:0,revision:1});
  assert.equal(await archive.getByRole('button', exact('Cancel operation')).count(), 0);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Maintenance fits the viewport');
  await page.screenshot({path:path.join(output,`maintenance-events-${width}x${height}.png`),animations:'disabled'});
}
