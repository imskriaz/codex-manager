import assert from 'node:assert/strict';
import path from 'node:path';

export async function checkImagesUi(page,{origin,parentId,width,height,output}) {
  await page.goto(`${origin}/workspace/${parentId}`);
  const trigger=page.getByRole('button',{name:'Preview Attachment preview',exact:true});
  const box=page.locator('.cli-image-lightbox');
  await trigger.click(); await box.waitFor();
  const original=box.getByRole('link',{name:'Download image',exact:true});
  assert.equal(await original.innerText(),'','Original image is an accessible icon');
  assert.equal(await original.locator('svg').count(),1);
  assert.ok(await original.getAttribute('download'), 'Image preview exposes a download filename');
  const first=await original.getAttribute('href');
  await box.locator('img').click(); assert.equal(await box.isVisible(),true,'Clicking the image keeps the preview open');
  assert.equal(await box.locator('.cli-image-lightbox-toolbar').count(),1,'There is one toolbar at the top');
  const beforeZoom=await box.locator('img').boundingBox(),beforeToolbar=await box.locator('.cli-image-lightbox-toolbar').boundingBox();
  const pageScale=await page.evaluate(()=>({width:innerWidth,scale:visualViewport.scale}));
  await box.getByRole('button',{name:'Zoom image',exact:true}).click();
  const afterZoom=await box.locator('img').boundingBox(),afterToolbar=await box.locator('.cli-image-lightbox-toolbar').boundingBox();
  assert.ok(afterZoom.width>=beforeZoom.width*1.9&&afterZoom.height>=beforeZoom.height*1.9,'Zoom enlarges the image itself');
  assert.deepEqual(afterToolbar,beforeToolbar,'Image zoom leaves the toolbar fixed');
  assert.deepEqual(await page.evaluate(()=>({width:innerWidth,scale:visualViewport.scale})),pageScale,'Image zoom never changes page scale');
  await box.getByRole('button',{name:'Fit image',exact:true}).click();
  await box.getByRole('button',{name:'Next image',exact:true}).click();
  assert.notEqual(await original.getAttribute('href'),first,'Original follows the selected gallery image');
  await box.getByText('2 / 3',{exact:true}).waitFor();
  await box.getByRole('button',{name:'Zoom image',exact:true}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Zoom does not create page overflow');
  if(width===320) assert.ok(await box.locator('.cli-image-stage').evaluate(stage=>stage.scrollWidth>stage.clientWidth),'Wide images scroll inside their viewing area');
  await box.getByRole('button',{name:'Fit image',exact:true}).click();

  await original.focus();
  await page.keyboard.press('ArrowRight');
  await box.getByText('3 / 3',{exact:true}).waitFor();
  assert.notEqual(await original.getAttribute('href'),first,'Gallery includes images from a different session message');
  await page.keyboard.press('ArrowRight');
  await box.getByText('1 / 3',{exact:true}).waitFor();
  await page.keyboard.press('ArrowLeft');
  await box.getByText('3 / 3',{exact:true}).waitFor();
  const bounds=await box.locator('.cli-image-lightbox-toolbar').boundingBox();
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=width+1,'Compact image actions fit the viewport');
  const actions=await box.getByRole('group',{name:'Image controls',exact:true}).boundingBox();
  const controls=await box.locator('.cli-image-lightbox-actions :is(button,a)').evaluateAll(items=>items.map(item=>{const r=item.getBoundingClientRect();return {y:r.y,height:r.height,width:r.width};}));
  assert.ok(controls.every(control=>Math.abs(control.height-controls[0].height)<1&&Math.abs(control.y-controls[0].y)<1),'Image actions share a size and baseline: '+JSON.stringify(controls));
  assert.ok(actions.x>=bounds.x&&actions.x+actions.width<=bounds.x+bounds.width,'The grouped actions remain inside the toolbar');

  await page.screenshot({path:path.join(output,`images-${width}x${height}.png`),animations:'disabled'});
  await box.locator('.cli-image-stage').click({position:{x:2,y:2}});
  await box.waitFor({state:'detached'});
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Preview Attachment preview');
  await trigger.click(); await box.locator('img').evaluate(img=>img.dispatchEvent(new Event('error')));
  await box.getByRole('alert').waitFor();
  assert.equal(await original.getAttribute('href'),first,'Failed previews keep the original available');
  await page.keyboard.press('Escape'); await box.waitFor({state:'detached'});
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Preview Attachment preview');
  await page.locator('.cli-message-markdown img').first().press('Enter');
  await box.getByText('1 / 3',{exact:true}).waitFor();
  await page.keyboard.press('ArrowLeft');await box.getByText('3 / 3',{exact:true}).waitFor();
  await page.keyboard.press('Escape');await box.waitFor({state:'detached'});
  await page.getByRole('link',{name:'Image file',exact:true}).press('Enter');
  const fileTrigger=page.getByRole('button',{name:'Preview preview.png',exact:true});
  await fileTrigger.click(); await box.waitFor();
  assert.equal(await original.getAttribute('href'),first,'Workspace images use the same preview and original action');
  await box.locator('img').click(); assert.equal(await box.isVisible(),true);
  await box.locator('.cli-image-stage').click({position:{x:2,y:2}}); await box.waitFor({state:'detached'});
  assert.equal(await fileTrigger.isVisible(),true,'Outside click returns to the workspace file');
}
